def set_cell_font(cell, text, font_name="黑体", font_size=10.5, bold=False):
    """设置单元格字体"""
    cell.text = ""
    run = cell.paragraphs[0].add_run(text)
    run.font.name = font_name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), font_name)
    run.font.size = Pt(font_size)
    run.font.bold = bold

def add_heading(doc, text, level=1):
    """添加标题（黑体）"""
    heading = doc.add_heading(text, level=level)
    for run in heading.runs:
        run.font.name = "黑体"
        run._element.rPr.rFonts.set(qn('w:eastAsia'), "黑体")
        run.font.color.rgb = RGBColor(0, 0, 0)
    return heading

def add_paragraph(doc, text, indent=False, bold=False, font_size=12):
    """添加正文段落（黑体，首行缩进）"""
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Cm(0.74)
    run = p.add_run(text)
    run.font.name = "黑体"
    run._element.rPr.rFonts.set(qn('w:eastAsia'), "黑体")
    run.font.size = Pt(font_size)
    run.font.bold = bold
    p.paragraph_format.line_spacing = 1.5
    return p

def add_table(doc, headers, rows):
    """添加表格"""
    table = doc.add_table(rows=len(rows)+1, cols=len(headers))
    table.style = 'Table Grid'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    # 表头
    for i, h in enumerate(headers):
        set_cell_font(table.rows[0].cells[i], h, bold=True, font_size=10.5)
        table.rows[0].cells[i].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    # 数据行
    for r_idx, row in enumerate(rows):
        for c_idx, val in enumerate(row):
            set_cell_font(table.rows[r_idx+1].cells[c_idx], str(val), font_size=10.5)
            table.rows[r_idx+1].cells[c_idx].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    return table

